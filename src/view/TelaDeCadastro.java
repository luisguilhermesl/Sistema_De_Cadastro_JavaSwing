    private void CarregarDadosUsuario() throws SQLException {
        UsuarioDAO usuarioDao = new UsuarioDAO();
        List<Usuario> usuarios = usuarioDao.getUsuarios();
        String[][] info = new String[usuarios.size()][5];

        //Preenchendo a tabela (colunas e linhas)
        for (int i = 0; i < usuarios.size(); i++) {
            info[i][0] = String.valueOf(usuarios.get(i).getId());
            info[i][1] = usuarios.get(i).getNome();
            info[i][2] = usuarios.get(i).getSobrenome();
            info[i][3] = usuarios.get(i).getEmail();
            info[i][4] = usuarios.get(i).getCidade();
        }
        String[] nomeColuna = {"Id", "Nome", "Sobrenome", "Email", "Cidade"};
        tabela.setModel(new javax.swing.table.DefaultTableModel(info, nomeColuna));
    }
