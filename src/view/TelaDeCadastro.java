    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed

        String addNome = nomeTF.getText();
        String addSobrenome = snomeTF.getText();
        String addEmail = emailTF.getText();
        String addCidade = cidadeTF.getText();

        if (addNome.isEmpty() || addSobrenome.isEmpty() || addEmail.isEmpty() || addCidade.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor preencha todos os campos", "ERRO", JOptionPane.ERROR_MESSAGE);
        } else {
            Usuario novoUsuario = new Usuario(0, addNome, addSobrenome, addEmail, addCidade);
            UsuarioDAO usuarioDao;

            try {
                usuarioDao = new UsuarioDAO();
                int res = usuarioDao.InserirUsuario(novoUsuario);
                if (res == 1) {
                    JOptionPane.showMessageDialog(this, "Usuário criado com sucesso!", "SUCESSO", JOptionPane.INFORMATION_MESSAGE);
                    this.LimparFormulario();
                    CarregarDadosUsuario();
                } else {
                    JOptionPane.showMessageDialog(this, "Erro ocorrido ao inserir o usuário", "ERRO", JOptionPane.ERROR_MESSAGE);
                }
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "ERRO", JOptionPane.ERROR_MESSAGE);
            }
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        String addNome = nomeTF.getText();
        String addSobrenome = snomeTF.getText();
        String addEmail = emailTF.getText();
        String addCidade = cidadeTF.getText();

        if (addNome.isEmpty() || addSobrenome.isEmpty() || addEmail.isEmpty() || addCidade.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor preencha todos os campos", "ERRO", JOptionPane.ERROR_MESSAGE);
        } else {
            if (idUsuarioSelecionado != -1) {
                Usuario AtualizarUsuario = new Usuario(idUsuarioSelecionado, addNome, addSobrenome, addEmail, addCidade);
                UsuarioDAO usuarioDao;

                try {
                    usuarioDao = new UsuarioDAO();
                    int res = usuarioDao.atualizarUsuario(AtualizarUsuario);
                    if (res == 1) {
                        JOptionPane.showMessageDialog(this, "Usuário atualizado com sucesso!", "SUCESSO", JOptionPane.INFORMATION_MESSAGE);
                        this.LimparFormulario();
                        CarregarDadosUsuario();
                        idUsuarioSelecionado = -1;
                    } else {
                        JOptionPane.showMessageDialog(this, "Erro ocorrido ao atualizar o usuário", "ERRO", JOptionPane.ERROR_MESSAGE);
                    }
                } catch (SQLException e) {
                    JOptionPane.showMessageDialog(this, e.getMessage(), "ERRO", JOptionPane.ERROR_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao atualizar", "ERRO", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnDeletarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeletarActionPerformed
        if (idUsuarioSelecionado != -1) {
            int confirmacao = JOptionPane.showConfirmDialog(this, "Você tem certeza que quer deletar esse usuário?", "Confirme a ação", JOptionPane.YES_NO_CANCEL_OPTION);
            if (confirmacao == JOptionPane.YES_OPTION) {
                UsuarioDAO usuarioDao;
                try {
                    usuarioDao = new UsuarioDAO();
                    usuarioDao.deleteUsuario(idUsuarioSelecionado);
                    JOptionPane.showMessageDialog(this, "Usuário deletado com sucesso!", "SUCESSO", JOptionPane.INFORMATION_MESSAGE);
                    this.LimparFormulario();
                    CarregarDadosUsuario();
                    idUsuarioSelecionado = -1;
                } catch (SQLException e) {
                    JOptionPane.showMessageDialog(this, "Erro ao deletar", "ERRO", JOptionPane.ERROR_MESSAGE);
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Nenhum usuário selecionado", "ERRO", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDeletarActionPerformed

    private void tabelaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaMouseClicked
        int linhaSelecionada = tabela.getSelectedRow();
        if (linhaSelecionada != -1) {
            idUsuarioSelecionado = Integer.parseInt(tabela.getValueAt(linhaSelecionada, 0).toString());
            nomeTF.setText(tabela.getValueAt(linhaSelecionada, 1).toString());
            snomeTF.setText(tabela.getValueAt(linhaSelecionada, 2).toString());
            emailTF.setText(tabela.getValueAt(linhaSelecionada, 3).toString());
            cidadeTF.setText(tabela.getValueAt(linhaSelecionada, 4).toString());
        }
    }//GEN-LAST:event_tabelaMouseClicked

